INTRODUCTION = (
    "Many processes can be described by using dynamical systems. The main idea "
    "here is that the state of a system in the current moment may be derived by "
    "knowing the state of the system at the previous moment(s) of time. If the "
    "time t is measured continuously then we are talking about continuous "
    "dynamical systems. If the time is measured discretely (only at certain "
    "points), then we are talking about discrete dynamical systems.\n\n"
    "In this project we will explore the connection between fractals and matrix "
    "(linear) mappings in the form of the so-called Chaos Game. The Chaos Game "
    "is an algorithm first proposed by M. Barnsley in his book \"Fractals "
    "everywhere\".\n\n"
    "The basic idea of the Chaos Game is simple. Pick n points on the plane "
    "(say, vertices of a regular n-gon), and a number r, 0 < r < 1. Pick a "
    "random point inside the polygon. Then repeat the following steps: pick a "
    "polygon vertex at random and draw the next point at a fraction r of the "
    "distance between the current point and the chosen vertex of the polygon. "
    "Repeat the process with the new point.\n\n"
    "This process can be written in the form of the following linear mapping. "
    "Let x = (x1, x2) be the current point, and let v = (v1, v2) be the "
    "selected vertex of the polygon. Then the next point can be generated by "
    "using the linear mapping T:\n\n"
    "    T(x) = [r 0; 0 r] (x - v) + v\n\n"
    "Here T(x) is the next point. Repeated many times, this process sometimes "
    "(but not always) produces a fractal. The mapping T can change from "
    "iteration to iteration or can be picked at random with different "
    "probabilities."
)

